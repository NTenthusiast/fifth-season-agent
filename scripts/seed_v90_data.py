def main() -> None:
    client = get_supabase_client()

    # 0) 修复 v9.0 测试中误改的项目 1 摘要
    p1 = one(client.table("fs_projects").select("id,summary").eq("id", 1).execute())
    if p1 and p1.get("summary") == "测试写入标记":
        client.table("fs_projects").update({"summary": "标注校内无障碍通道与设施，已完成两栋教学楼的测绘与调研。"}).eq("id", 1).execute()
        print("[fix] 已恢复项目 1 摘要")

    # 1) 新增休眠项目（按标题判重）
    existing = {p["title"] for p in (client.table("fs_projects").select("title").execute().data or [])}
    added = 0
    for title, summary, tags, skills, founder_id, reason, school in NEW_PROJECTS:
        if title in existing:
            continue
        client.table("fs_projects").insert({
            "title": title,
            "summary": summary,
            "domain_tags": tags,
            "required_skills": skills,
            "stage": "winter",
            "founder_id": founder_id,
            "owner_id": founder_id,
            "hibernate_reason": reason,
            "hibernate_at": "2025-04-01T10:00:00+00:00",
            "school": school,
        }).execute()
        added += 1
    print(f"[projects] 新增 {added} 个休眠项目")

    # 2) 示范投票（既有示范用户，跳过已投）
    winter = client.table("fs_projects").select("id").eq("stage", "winter").execute().data or []
    voters = ["林小满", "陈知夏", "晚晴", "林晚秋", "慕浅", "小柯", "顾清扬", "唐子昂", "罗雨薇", "肖承宇", "桑若曦", "路星辞", "柯梦桐", "卫子谦"]
    existing_votes = {(v["project_id"], v["voter_nickname"]) for v in (client.table("fs_votes").select("project_id,voter_nickname").execute().data or [])}
    vote_added = 0
    for i, p in enumerate(winter):
        pid = p["id"]
        # 每个项目投 0-3 票（错落分布，让排序有层次）
        for v in voters[(i * 3) % 10: (i * 3) % 10 + (i % 4)]:
            if (pid, v) not in existing_votes:
                client.table("fs_votes").insert({"project_id": pid, "voter_nickname": v}).execute()
                vote_added += 1
    print(f"[votes] 新增 {vote_added} 条示范投票")

    # 3) 精选传承故事
    existing_stories = {s["title"] for s in (client.table("fs_curated_stories").select("title").execute().data or [])}
    story_added = 0
    for idx, (title, school, era, tags, summary, full, url, source, featured) in enumerate(STORIES):
        if title in existing_stories:
            continue
        client.table("fs_curated_stories").insert({
            "title": title,
            "school": school,
            "era": era,
            "tags": tags,
            "summary": summary,
            "story_full": full,
            "source_url": url,
            "source_name": source,
            "is_featured": featured,
            "sort_no": idx,
        }).execute()
        story_added += 1
    print(f"[stories] 新增 {story_added} 篇传承故事")

    total = len(client.table("fs_projects").select("id").execute().data or [])
    winter_total = len(client.table("fs_projects").select("id").eq("stage", "winter").execute().data or [])
    story_total = len(client.table("fs_curated_stories").select("id").execute().data or [])
    print(f"[done] 项目总数 {total}（休眠 {winter_total}），故事 {story_total} 篇")


if __name__ == "__main__":
    main()
