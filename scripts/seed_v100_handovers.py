def main() -> None:
    client = get_supabase_client()

    # 已有交接包的项目跳过
    existing = {
        int(r["project_id"])
        for r in (client.table("fs_handover_packages").select("project_id").execute().data or [])
    }
    print("existing packages:", sorted(existing))

    # 全部项目默认授权公开交接包（存量公开卡：点开即可获取）
    all_ids = [int(r["id"]) for r in (client.table("fs_projects").select("id").execute().data or [])]
    client.table("fs_projects").update({"handover_public": True}).in_("id", all_ids).execute()

    inserted = 0
    for pid, pkg in PKGS.items():
        if pid in existing:
            continue
        clean = {}
        for k, v in pkg.items():
            items = [str(i).strip() for i in v if str(i).strip()]
            clean[k] = items
        clean["reusable_resources"].extend(
            [
                f"【授权范围】{GOV['authorization_scope']}",
                f"【资源有效期】{GOV['resource_valid_until']}",
                f"【原团队权益】{GOV['founder_rights']}",
            ]
        )
        row = {
            "project_id": int(pid),
            **{k: json.dumps(v, ensure_ascii=False) for k, v in clean.items()},
        }
        client.table("fs_handover_packages").insert(row).execute()
        inserted += 1
        print(f"inserted handover for project {pid}")

    # 校验
    total = client.table("fs_handover_packages").select("project_id").execute().data or []
    projects = client.table("fs_projects").select("id").execute().data or []
    pub = client.table("fs_projects").select("id, handover_public").eq("handover_public", True).execute().data or []
    print(f"packages={len(total)} projects={len(projects)} handover_public=True={len(pub)} inserted={inserted}")
    missing = [p["id"] for p in projects if p["id"] not in {int(t["project_id"]) for t in total}]
    print("missing:", missing or "NONE")


if __name__ == "__main__":
    main()
